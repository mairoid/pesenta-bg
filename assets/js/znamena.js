        '<linearGradient id="' + GRAD + '" x1="0" y1="0" x2="1" y2="1">' +
          '<stop offset="0" stop-color="#ff4d8d"/>' +
          '<stop offset="1" stop-color="#ffa14d"/>' +
        "</linearGradient>" +
      "</defs></svg>";
    kade.insertBefore(k.firstChild, kade.firstChild);
